local cjson=require("cjson.safe")
dofile("/workspace/tests/push/openresty/mock_google.lua")
local oauth=require("push.oauth")
local file=assert(io.open("/config/firebase.json"));local sa=assert(cjson.decode(file:read("*a")));file:close()
local cache=ngx.shared.push_oauth_tokens
local stats=ngx.shared.test_stats
local locks=ngx.shared.push_locks
local count=0
local function check(name,fn)
    cache:flush_all();cache:flush_expired();stats:flush_all();stats:flush_expired()
    fn();count=count+1;print("PASS "..name)
end
check("first OAuth request and real JWT signing",function()
    assert(oauth.get(sa)=="secret-oauth-access");assert(stats:get("oauth_calls")==1)
end)
check("cache hit creates no new JWT or OAuth request",function()
    assert(oauth.get(sa));assert(oauth.get(sa));assert(stats:get("oauth_calls")==1)
end)
check("expiry safety margin and renewal",function()
    stats:set("expires",1)
    assert(oauth.get(sa));local ttl=cache:ttl("oauth:"..oauth.identity(sa));assert(ttl>0 and ttl<1)
    ngx.sleep(1.05);assert(oauth.get(sa));assert(stats:get("oauth_calls")==2)
end)
check("concurrent refresh single-flight",function()
    local threads={}
    for i=1,20 do threads[i]=ngx.thread.spawn(function() assert(oauth.get(sa)) end) end
    for _,t in ipairs(threads) do assert(ngx.thread.wait(t)) end
    assert(stats:get("oauth_calls")==1)
end)
check("failed refresh releases lock and recovers",function()
    stats:set("oauth_mode","fail");local token,category=oauth.get(sa)
    assert(not token and category=="TEMPORARY_FAILURE")
    assert(not locks:get("oauth:"..oauth.identity(sa)))
    stats:delete("oauth_mode");cache:delete("oauth:"..oauth.identity(sa)..":failure")
    assert(oauth.get(sa));assert(stats:get("oauth_calls")==2)
end)
check("exception releases lock without exposing secrets",function()
    stats:set("oauth_mode","throw");local token,category=oauth.get(sa)
    assert(not token and category=="AUTH_ERROR")
    assert(not locks:get("oauth:"..oauth.identity(sa)))
end)
check("failure cooldown prevents refresh stampede",function()
    stats:set("oauth_mode","fail");assert(not oauth.get(sa));assert(not oauth.get(sa))
    assert(stats:get("oauth_calls")==1)
end)
check("identity rotation separates cached access tokens",function()
    assert(oauth.get(sa));local other={client_email="other@test",project_id=sa.project_id,private_key=sa.private_key}
    assert(oauth.get(other));assert(stats:get("oauth_calls")==2)
end)
check("invalidate only rejected generation",function()
    assert(oauth.get(sa));oauth.invalidate(sa,"old-access")
    assert(oauth.get(sa));assert(stats:get("oauth_calls")==1)
    oauth.invalidate(sa,"secret-oauth-access");assert(not oauth.get(sa))
    assert(stats:get("oauth_calls")==1)
    cache:delete("oauth:"..oauth.identity(sa)..":failure")
    assert(oauth.get(sa));assert(stats:get("oauth_calls")==2)
end)
print("OAUTH_TESTS_PASSED="..count)
